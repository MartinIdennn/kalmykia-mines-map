const reset = db.transaction(() => {
  db.exec('DELETE FROM donations; DELETE FROM budget_items; DELETE FROM photos; DELETE FROM mines;');
  db.exec("DELETE FROM sqlite_sequence WHERE name IN ('mines','photos','budget_items','donations');");

  const insMine = db.prepare(
    'INSERT INTO mines (name, lat, lng, short, description, goal) VALUES (?,?,?,?,?,?)'
  );
  const insPhoto = db.prepare('INSERT INTO photos (mine_id, url) VALUES (?,?)');
  const insBudget = db.prepare('INSERT INTO budget_items (mine_id, item, amount) VALUES (?,?,?)');
  const insDonation = db.prepare(
    'INSERT INTO donations (mine_id, name, amount, created_at) VALUES (?,?,?,?)'
  );

  MINES.forEach((m, idx) => {
    const info = insMine.run(m.name, m.lat, m.lng, m.short, m.description, m.goal);
    const mineId = info.lastInsertRowid;

    // Случайные тематические фото рудников/карьеров (loremflickr по тегам);
    // lock делает картинку стабильной, но разной для каждого фото.
    m.photos.forEach((_, pi) => {
      const lock = mineId * 10 + pi + 1;
      insPhoto.run(
        mineId,
        `https://loremflickr.com/800/500/quarry,mine,mining,openpit?lock=${lock}`
      );
    });

    m.budget.forEach((b) => insBudget.run(mineId, b.item, b.amount));

    m.donors.forEach((d, di) => {
      // разнесём время демо-донатов на несколько часов назад
      const at = new Date(Date.now() - (di + 1) * 3600 * 1000).toISOString().replace('T', ' ').slice(0, 19);
      insDonation.run(mineId, d.name, d.amount, at);
    });
  });
});

reset();

